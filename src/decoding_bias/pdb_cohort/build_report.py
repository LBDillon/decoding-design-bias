def variance_decomposition():
    cv = pd.read_csv(COHORT_VD)
    ctrl = pd.read_csv(AF2_VD)
    cv = cv[cv["model"].isin(ORDER)].set_index("model").reindex(ORDER).reset_index()

    tcols = {"model": "Model", "type": "Type", "n": "n", "R2_Biophys": "Biophys $R^2$",
             "dSpecies_given_family_biophys": "$\\Delta$spec (raw)",
             "residual_species_R2_adj": "$\\Delta$spec (adj)",
             "species_attenuation": "atten.",
             "species_effect_retention_given_family_biophys": "retention",
             "species_p_given_family_biophys": "$p$"}
    keep = list(tcols)
    to_tex(cv[keep].rename(columns=tcols), TAB / "table_vd_cohort.tex",
           "Score-variance decomposition on the experimental-PDB cohort (per-model complete case; "
           "14-feature biophysics, protein family, species). $\\Delta$spec = residual species "
           "variance beyond family+biophysics; retention = within-family per-species effect "
           "retention (Simpson's check).", "tab:pdb-vd")

    cmp = ctrl[["model", "type", "PDB_resid_raw", "AF2_resid_raw_mean", "AF2_resid_raw_sd",
                "PDB_resid_adj", "AF2_resid_adj_mean", "PDB_retention", "AF2_retention_mean"]].copy()
    cmp["model"] = pd.Categorical(cmp["model"], ORDER, ordered=True)
    cmp = cmp.sort_values("model")
    ren = {"model": "Model", "type": "Type", "PDB_resid_raw": "$\\Delta$spec PDB",
           "AF2_resid_raw_mean": "$\\Delta$spec AF2", "AF2_resid_raw_sd": "AF2 sd",
           "PDB_resid_adj": "adj PDB", "AF2_resid_adj_mean": "adj AF2",
           "PDB_retention": "ret.\\ PDB", "AF2_retention_mean": "ret.\\ AF2"}
    to_tex(cmp.rename(columns=ren), TAB / "table_vd_pdb_vs_af2.tex",
           "Residual species variance: experimental-PDB cohort vs matched AF2 subsample "
           "(AF2 = mean over 30 N- and composition-matched draws).", "tab:pdb-vs-af2-vd")

    # figure: residual species (raw) PDB vs AF2-matched + retention
    fig, ax = plt.subplots(1, 2, figsize=(13, 5.2))
    m = ctrl.set_index("model").reindex(ORDER)
    x = np.arange(len(ORDER)); w = 0.4
    cols = [TYPE_C[PANEL[k][1]] for k in ORDER]
    ax[0].bar(x - w / 2, m["PDB_resid_raw"], w, label="PDB cohort", color="#1976D2")
    ax[0].bar(x + w / 2, m["AF2_resid_raw_mean"], w, yerr=m["AF2_resid_raw_sd"],
              label="AF2 matched", color="#F57C00", capsize=2)
    ax[0].set_ylabel("residual species $R^2$ (raw)")
    ax[0].set_title("Residual species variance beyond family+biophysics")
    ax[1].bar(x - w / 2, m["PDB_retention"], w, label="PDB cohort", color="#1976D2")
    ax[1].bar(x + w / 2, m["AF2_retention_mean"], w, yerr=m["AF2_retention_sd"],
              label="AF2 matched", color="#F57C00", capsize=2)
    ax[1].axhline(0, color="k", lw=0.6)
    ax[1].set_ylabel("within-family per-species retention")
    ax[1].set_title("Simpson's-check retention (→1 genuine, →0 family-driven)")
    seq_start = [PANEL[k][1] for k in ORDER].index("sequence")
    for a in ax:
        a.set_xticks(x); a.set_xticklabels(ORDER, rotation=55, ha="right", fontsize=8)
        a.axvline(seq_start - 0.5, color="k", ls="--", lw=0.8, alpha=0.4)
        a.legend(fontsize=9); a.grid(axis="y", alpha=0.2)
    fig.suptitle("Variance decomposition: experimental-PDB cohort vs matched AF2", fontsize=13)
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    fig.savefig(FIG / "fig_variance_decomposition.png", dpi=150)
    fig.savefig(FIG / "fig_variance_decomposition.pdf"); plt.close(fig)
    print("wrote fig_variance_decomposition + table_vd_cohort + table_vd_pdb_vs_af2")


# ---------------------------------------------------------------- ELO
def elo():
    col2name = {v[0]: k for k, v in PANEL.items()}
    ce = pd.read_csv(COHORT_ELO)
    ce["Model"] = ce["model"].map(lambda c: col2name.get(c, c))
    ce = ce[ce["Model"].isin(ORDER)].copy()
    ce["Model"] = pd.Categorical(ce["Model"], ORDER, ordered=True)
    ce = ce.sort_values("Model")
    tcols = {"Model": "Model", "Archaea": "Archaea", "Bacteria": "Bacteria",
             "Eukaryota": "Eukaryota", "Arch_minus_Euk": "Arch$-$Euk", "top_domain": "top"}
    to_tex(ce[list(tcols)].rename(columns=tcols), TAB / "table_elo.tex",
           "Mean species Elo by domain on the experimental-PDB cohort (unweighted; 50 permutations) "
           "and the Archaea$-$Eukaryota gap.", "tab:pdb-elo", floatfmt="%.0f")

    ctrl = pd.read_csv(AF2_ELO).set_index("model").reindex(ORDER)
    fig, ax = plt.subplots(figsize=(11, 5.4))
    x = np.arange(len(ORDER)); w = 0.4
    pdbgap = ce.set_index("Model").reindex(ORDER)["Arch_minus_Euk"]
    ax.bar(x - w / 2, pdbgap.values, w, label="PDB cohort", color="#1976D2")
    ax.bar(x + w / 2, ctrl["AF2_arch_minus_euk_mean"], w, yerr=ctrl["AF2_arch_minus_euk_sd"],
           label="AF2 matched", color="#F57C00", capsize=2)
    ax.axhline(0, color="k", lw=0.8)
    seq_start = [PANEL[k][1] for k in ORDER].index("sequence")
    ax.axvline(seq_start - 0.5, color="k", ls="--", lw=0.8, alpha=0.4)
    ax.set_xticks(x); ax.set_xticklabels(ORDER, rotation=55, ha="right")
    ax.set_ylabel("Archaea − Eukaryota Elo gap")
    ax.set_title("Species Elo: Archaea−Eukaryota preference, PDB cohort vs matched AF2\n"
                 "(>0 prefers Archaea, <0 prefers Eukaryota)")
    ax.legend(); ax.grid(axis="y", alpha=0.2)
    fig.tight_layout()
    fig.savefig(FIG / "fig_elo.png", dpi=150); fig.savefig(FIG / "fig_elo.pdf"); plt.close(fig)
    print("wrote fig_elo + table_elo")


def main():
    present = [m for m in ORDER if PANEL[m][0] in pd.read_csv(COHORT_SCORED, nrows=1).columns]
    pdb = export_pdb_pca_ready()
    af2 = build_matched_af2(present)
    composition(pdb, af2)
    property_importance(pdb, af2, present)
    variance_decomposition()
    elo()
    print("\nReport built under pdb_robustness/")


if __name__ == "__main__":
    main()
