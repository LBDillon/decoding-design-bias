def _fmt(v, floatfmt):
    try:
        if pd.isna(v):
            return "--"
    except (TypeError, ValueError):
        pass
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, float):
        return floatfmt % v
    # string cell: escape underscores that are not already escaped (feature names)
    return str(v).replace("\\_", "§").replace("_", "\\_").replace("§", "\\_")


def to_tex(df, path, caption, label, floatfmt="%.3f"):
    """Minimal booktabs tabular writer (no jinja2 dependency). Column headers are
    assumed already LaTeX-safe; cell strings are escaped for %, &, _ only when not
    already containing a backslash command."""
    ncol = df.shape[1]
    align = "l" + "r" * (ncol - 1)
    head = " & ".join(str(c) for c in df.columns) + " \\\\"
    lines = []
    for _, row in df.iterrows():
        cells = [_fmt(v, floatfmt) for v in row]
        lines.append(" & ".join(cells) + " \\\\")
    body = ("\\begin{tabular}{" + align + "}\n\\toprule\n" + head + "\n\\midrule\n"
            + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")
    tex = ("% auto-generated by pdb_robustness/build_report.py\n"
           "\\begin{table}[ht]\\centering\\small\n"
           f"\\caption{{{caption}}}\\label{{{label}}}\n{body}\\end{{table}}\n")
    path.write_text(tex)


# ---------------------------------------------------------------- data exports
def build_matched_af2(present_models):
    main = pd.read_csv(MAIN, low_memory=False)
    pool = main[main.domain.isin(TARGET)]
    pool = pool[~pool["broad_function"].astype(str).str.contains("ribosom", case=False)]
    cols_needed = FEATS + ["protein_family", "species"] + [PANEL[m][0] for m in present_models]
    pool = pool.dropna(subset=[c for c in cols_needed if c in pool.columns])
    parts = [pool[pool.domain == d].sample(n=min(n, int((pool.domain == d).sum())), random_state=SEED)
             for d, n in TARGET.items()]
    sub = pd.concat(parts).reset_index(drop=True)
    keep = (["Entry", "domain", "species", "protein_family", "broad_function"]
            + (["avg_plddt"] if "avg_plddt" in sub.columns else [])
            + FEATS + [c for c in sub.columns if c.endswith("_score")])
    sub = sub[[c for c in keep if c in sub.columns]]
    sub = sub.drop(columns=[c for c in sub.columns if "triflow" in c.lower()])  # excluded from analysis
    out = DATA / "matched_af2_cohort_pca_ready.csv"
    sub.to_csv(out, index=False)
    print(f"matched AF2 cohort -> {out.name}  (n={len(sub)}, seed={SEED})")
    return sub


def export_pdb_pca_ready():
    df = pd.read_csv(COHORT_SCORED)
    df = df.drop(columns=[c for c in df.columns if "triflow" in c.lower()])  # excluded from analysis
    out = DATA / "pdb_cohort_pca_ready.csv"
    df.to_csv(out, index=False)
    print(f"PDB cohort        -> {out.name}  (n={len(df)})")
    return df


# ---------------------------------------------------------------- composition
def composition(pdb, af2):
    main = pd.read_csv(MAIN, low_memory=False)
    main = main[main.domain.isin(TARGET)]

    def summ(df, name):
        n = len(df)
        dom = df["domain"].value_counts(normalize=True) * 100
        rib = df["broad_function"].astype(str).str.contains("ribosom", case=False).mean() * 100
        return dict(cohort=name, n=n,
                    pct_Archaea=dom.get("Archaea", 0), pct_Bacteria=dom.get("Bacteria", 0),
                    pct_Eukaryota=dom.get("Eukaryota", 0), pct_ribosomal=rib,
                    median_len=df["sequence_length"].median(), median_pI=df["isoelectric_point"].median(),
                    n_species=df["species"].nunique(), n_families=df["protein_family"].nunique())

    rows = [summ(pdb, "PDB cohort (experimental)"), summ(af2, "AF2 matched (N=876)"),
            summ(main, "AF2 full (3-domain)")]
    comp = pd.DataFrame(rows)
    tcols = {"cohort": "Cohort", "n": "n", "pct_Archaea": "\\% Arch", "pct_Bacteria": "\\% Bact",
             "pct_Eukaryota": "\\% Euk", "pct_ribosomal": "\\% ribo", "median_len": "med.\\ len",
             "median_pI": "med.\\ pI", "n_species": "species", "n_families": "families"}
    to_tex(comp.rename(columns=tcols), TAB / "table_composition.tex",
           "Composition of the experimental-PDB cohort, the matched AF2 subsample, and the full "
           "3-domain AF2 set.", "tab:pdb-composition", floatfmt="%.1f")

    # figure: domain proportions, ribosomal %, length & pI distributions
    fig, ax = plt.subplots(2, 2, figsize=(11, 8))
    labels = ["PDB cohort", "AF2 matched", "AF2 full"]
    dfs = [pdb, af2, main]
    cpal = ["#1976D2", "#F57C00", "#9E9E9E"]
    # (a) domain proportions
    doms = ["Archaea", "Bacteria", "Eukaryota"]
    x = np.arange(len(doms)); w = 0.26
    for i, (df, lab) in enumerate(zip(dfs, labels)):
        p = df["domain"].value_counts(normalize=True) * 100
        ax[0, 0].bar(x + (i - 1) * w, [p.get(d, 0) for d in doms], w, label=lab, color=cpal[i])
    ax[0, 0].set_xticks(x); ax[0, 0].set_xticklabels(doms); ax[0, 0].set_ylabel("% of cohort")
    ax[0, 0].set_title("Domain composition (matched by design)"); ax[0, 0].legend(fontsize=8)
    # (b) ribosomal %
    ribs = [df["broad_function"].astype(str).str.contains("ribosom", case=False).mean() * 100 for df in dfs]
    ax[0, 1].bar(labels, ribs, color=cpal)
    ax[0, 1].set_ylabel("% ribosomal"); ax[0, 1].set_title("Ribosomal fraction")
    for i, v in enumerate(ribs):
        ax[0, 1].text(i, v + 0.4, f"{v:.0f}%", ha="center", fontsize=9)
    # (c) length
    for df, lab, c in zip(dfs, labels, cpal):
        ax[1, 0].hist(df["sequence_length"].clip(upper=1000), bins=40, histtype="step",
                      density=True, label=lab, color=c, lw=1.8)
    ax[1, 0].set_xlabel("sequence length (aa)"); ax[1, 0].set_ylabel("density")
    ax[1, 0].set_title("Length distribution"); ax[1, 0].legend(fontsize=8)
    # (d) pI
    for df, lab, c in zip(dfs, labels, cpal):
        ax[1, 1].hist(df["isoelectric_point"], bins=40, histtype="step",
                      density=True, label=lab, color=c, lw=1.8)
    ax[1, 1].set_xlabel("isoelectric point"); ax[1, 1].set_ylabel("density")
    ax[1, 1].set_title("Isoelectric-point distribution"); ax[1, 1].legend(fontsize=8)
    fig.suptitle("Cohort composition: experimental-PDB vs AF2 (matched & full)", fontsize=13)
    fig.tight_layout(rect=[0, 0, 1, 0.97])
    fig.savefig(FIG / "fig_composition.png", dpi=150); fig.savefig(FIG / "fig_composition.pdf")
    plt.close(fig)
    print("wrote fig_composition + table_composition")
    return comp


# ---------------------------------------------------------------- property importance
def property_importance(pdb, af2, present_models):
    spec = importlib.util.spec_from_file_location(
        "propimp", REPO / "paper_code" / "04_property_importance" / "property_importance.py")
    PI = importlib.util.module_from_spec(spec); spec.loader.exec_module(PI)
    models = {m: PANEL[m][0] for m in present_models}
    rp = PI.analyse(pdb, models, "PDB"); rp["cohort"] = "PDB"
    ra = PI.analyse(af2, models, "AF2"); ra["cohort"] = "AF2_matched"
    rp.to_csv(DATA / "property_importance_pdb.csv", index=False)
    ra.to_csv(DATA / "property_importance_af2_matched.csv", index=False)

    # table: top-3 properties by relative weight per model, both cohorts
    def top3(df):
        out = {}
        for m, g in df.groupby("model"):
            g = g.sort_values("rel_weight_pct", ascending=False).head(3)
            out[m] = ", ".join(f"{r.property} ({r.rel_weight_pct:.0f}\\%)" for r in g.itertuples())
        return out
    tp, ta = top3(rp), top3(ra)
    r2p = rp.groupby("model").model_R2.first(); r2a = ra.groupby("model").model_R2.first()
    rows = [dict(Model=m, **{"$R^2$ (PDB)": r2p.get(m, np.nan),
                             "Top properties (PDB)": tp.get(m, ""),
                             "$R^2$ (AF2)": r2a.get(m, np.nan),
                             "Top properties (AF2 matched)": ta.get(m, "")})
            for m in present_models if m in tp]
    to_tex(pd.DataFrame(rows), TAB / "table_property_importance.tex",
           "Top biophysical properties by Johnson relative weight (\\% of model $R^2$) for each "
           "model, on the experimental-PDB cohort vs the matched AF2 subsample.",
           "tab:pdb-propimp", floatfmt="%.2f")

    # figure: rel weight of the dominant structural feature (avg_cb_distance / rco) and a
    # composition feature (acidic_residue_fraction) - PDB vs AF2 - for all models
    feats_show = ["avg_cb_distance", "rco", "acidic_residue_fraction", "isoelectric_point"]
    fig, axes = plt.subplots(1, len(feats_show), figsize=(15, 5), sharey=True)
    x = np.arange(len(present_models)); w = 0.4
    for k, feat in enumerate(feats_show):
        pv = [rp[(rp.model == m) & (rp.property == feat)].rel_weight_pct.mean() for m in present_models]
        av = [ra[(ra.model == m) & (ra.property == feat)].rel_weight_pct.mean() for m in present_models]
        axes[k].bar(x - w / 2, pv, w, label="PDB", color="#1976D2")
        axes[k].bar(x + w / 2, av, w, label="AF2 matched", color="#F57C00")
        axes[k].set_title(feat, fontsize=10); axes[k].set_xticks(x)
        axes[k].set_xticklabels(present_models, rotation=60, ha="right", fontsize=7)
        if k == 0:
            axes[k].set_ylabel("relative weight (% of model R²)"); axes[k].legend(fontsize=8)
    fig.suptitle("Property→score importance: experimental-PDB vs matched AF2", fontsize=13)
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    fig.savefig(FIG / "fig_property_importance.png", dpi=150)
    fig.savefig(FIG / "fig_property_importance.pdf"); plt.close(fig)
    print("wrote fig_property_importance + table_property_importance")


