def _fmt(v, floatfmt):
    try:
        if pd.isna(v):
            return '--'
    except (TypeError, ValueError):
        pass
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, float):
        return floatfmt % v
    return str(v).replace('\\_', '§').replace('_', '\\_').replace('§', '\\_')
def to_tex(df, path, caption, label, floatfmt='%.3f'):
    """Minimal booktabs tabular writer (no jinja2 dependency). Column headers are
    assumed already LaTeX-safe; cell strings are escaped for %, &, _ only when not
    already containing a backslash command."""
    ncol = df.shape[1]
    align = 'l' + 'r' * (ncol - 1)
    head = ' & '.join((str(c) for c in df.columns)) + ' \\\\'
    lines = []
    for (_, row) in df.iterrows():
        cells = [_fmt(v, floatfmt) for v in row]
        lines.append(' & '.join(cells) + ' \\\\')
    body = '\\begin{tabular}{' + align + '}\n\\toprule\n' + head + '\n\\midrule\n' + '\n'.join(lines) + '\n\\bottomrule\n\\end{tabular}\n'
    tex = f'% auto-generated by pdb_robustness/build_report.py\n\\begin{{table}}[ht]\\centering\\small\n\\caption{{{caption}}}\\label{{{label}}}\n{body}\\end{{table}}\n'
    path.write_text(tex)
def build_matched_af2(present_models):
    main = pd.read_csv(MAIN, low_memory=False)
    pool = main[main.domain.isin(TARGET)]
    pool = pool[~pool['broad_function'].astype(str).str.contains('ribosom', case=False)]
    cols_needed = FEATS + ['protein_family', 'species'] + [PANEL[m][0] for m in present_models]
    pool = pool.dropna(subset=[c for c in cols_needed if c in pool.columns])
    parts = [pool[pool.domain == d].sample(n=min(n, int((pool.domain == d).sum())), random_state=SEED) for (d, n) in TARGET.items()]
    sub = pd.concat(parts).reset_index(drop=True)
    keep = ['Entry', 'domain', 'species', 'protein_family', 'broad_function'] + (['avg_plddt'] if 'avg_plddt' in sub.columns else []) + FEATS + [c for c in sub.columns if c.endswith('_score')]
    sub = sub[[c for c in keep if c in sub.columns]]
    sub = sub.drop(columns=[c for c in sub.columns if 'triflow' in c.lower()])
    out = DATA / 'matched_af2_cohort_pca_ready.csv'
    sub.to_csv(out, index=False)
    print(f'matched AF2 cohort -> {out.name}  (n={len(sub)}, seed={SEED})')
    return sub
