def property_importance(pdb, af2, present_models):
    spec = importlib.util.spec_from_file_location('propimp', REPO / 'paper_code' / '04_property_importance' / 'property_importance.py')
    PI = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(PI)
    models = {m: PANEL[m][0] for m in present_models}
    rp = PI.analyse(pdb, models, 'PDB')
    rp['cohort'] = 'PDB'
    ra = PI.analyse(af2, models, 'AF2')
    ra['cohort'] = 'AF2_matched'
    rp.to_csv(DATA / 'property_importance_pdb.csv', index=False)
    ra.to_csv(DATA / 'property_importance_af2_matched.csv', index=False)

    def top3(df):
        out = {}
        for (m, g) in df.groupby('model'):
            g = g.sort_values('rel_weight_pct', ascending=False).head(3)
            out[m] = ', '.join((f'{r.property} ({r.rel_weight_pct:.0f}\\%)' for r in g.itertuples()))
        return out
    (tp, ta) = (top3(rp), top3(ra))
    r2p = rp.groupby('model').model_R2.first()
    r2a = ra.groupby('model').model_R2.first()
    rows = [dict(Model=m, **{'$R^2$ (PDB)': r2p.get(m, np.nan), 'Top properties (PDB)': tp.get(m, ''), '$R^2$ (AF2)': r2a.get(m, np.nan), 'Top properties (AF2 matched)': ta.get(m, '')}) for m in present_models if m in tp]
    to_tex(pd.DataFrame(rows), TAB / 'table_property_importance.tex', 'Top biophysical properties by Johnson relative weight (\\% of model $R^2$) for each model, on the experimental-PDB cohort vs the matched AF2 subsample.', 'tab:pdb-propimp', floatfmt='%.2f')
    feats_show = ['avg_cb_distance', 'rco', 'acidic_residue_fraction', 'isoelectric_point']
    (fig, axes) = plt.subplots(1, len(feats_show), figsize=(15, 5), sharey=True)
    x = np.arange(len(present_models))
    w = 0.4
    for (k, feat) in enumerate(feats_show):
        pv = [rp[(rp.model == m) & (rp.property == feat)].rel_weight_pct.mean() for m in present_models]
        av = [ra[(ra.model == m) & (ra.property == feat)].rel_weight_pct.mean() for m in present_models]
        axes[k].bar(x - w / 2, pv, w, label='PDB', color='#1976D2')
        axes[k].bar(x + w / 2, av, w, label='AF2 matched', color='#F57C00')
        axes[k].set_title(feat, fontsize=10)
        axes[k].set_xticks(x)
        axes[k].set_xticklabels(present_models, rotation=60, ha='right', fontsize=7)
        if k == 0:
            axes[k].set_ylabel('relative weight (% of model R²)')
            axes[k].legend(fontsize=8)
    fig.suptitle('Property→score importance: experimental-PDB vs matched AF2', fontsize=13)
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    fig.savefig(FIG / 'fig_property_importance.png', dpi=150)
    fig.savefig(FIG / 'fig_property_importance.pdf')
    plt.close(fig)
    print('wrote fig_property_importance + table_property_importance')
