def composition(pdb, af2):
    main = pd.read_csv(MAIN, low_memory=False)
    main = main[main.domain.isin(TARGET)]

    def summ(df, name):
        n = len(df)
        dom = df['domain'].value_counts(normalize=True) * 100
        rib = df['broad_function'].astype(str).str.contains('ribosom', case=False).mean() * 100
        return dict(cohort=name, n=n, pct_Archaea=dom.get('Archaea', 0), pct_Bacteria=dom.get('Bacteria', 0), pct_Eukaryota=dom.get('Eukaryota', 0), pct_ribosomal=rib, median_len=df['sequence_length'].median(), median_pI=df['isoelectric_point'].median(), n_species=df['species'].nunique(), n_families=df['protein_family'].nunique())
    rows = [summ(pdb, 'PDB cohort (experimental)'), summ(af2, 'AF2 matched (N=876)'), summ(main, 'AF2 full (3-domain)')]
    comp = pd.DataFrame(rows)
    tcols = {'cohort': 'Cohort', 'n': 'n', 'pct_Archaea': '\\% Arch', 'pct_Bacteria': '\\% Bact', 'pct_Eukaryota': '\\% Euk', 'pct_ribosomal': '\\% ribo', 'median_len': 'med.\\ len', 'median_pI': 'med.\\ pI', 'n_species': 'species', 'n_families': 'families'}
    to_tex(comp.rename(columns=tcols), TAB / 'table_composition.tex', 'Composition of the experimental-PDB cohort, the matched AF2 subsample, and the full 3-domain AF2 set.', 'tab:pdb-composition', floatfmt='%.1f')
    (fig, ax) = plt.subplots(2, 2, figsize=(11, 8))
    labels = ['PDB cohort', 'AF2 matched', 'AF2 full']
    dfs = [pdb, af2, main]
    cpal = ['#1976D2', '#F57C00', '#9E9E9E']
    doms = ['Archaea', 'Bacteria', 'Eukaryota']
    x = np.arange(len(doms))
    w = 0.26
    for (i, (df, lab)) in enumerate(zip(dfs, labels)):
        p = df['domain'].value_counts(normalize=True) * 100
        ax[0, 0].bar(x + (i - 1) * w, [p.get(d, 0) for d in doms], w, label=lab, color=cpal[i])
    ax[0, 0].set_xticks(x)
    ax[0, 0].set_xticklabels(doms)
    ax[0, 0].set_ylabel('% of cohort')
    ax[0, 0].set_title('Domain composition (matched by design)')
    ax[0, 0].legend(fontsize=8)
    ribs = [df['broad_function'].astype(str).str.contains('ribosom', case=False).mean() * 100 for df in dfs]
    ax[0, 1].bar(labels, ribs, color=cpal)
    ax[0, 1].set_ylabel('% ribosomal')
    ax[0, 1].set_title('Ribosomal fraction')
    for (i, v) in enumerate(ribs):
        ax[0, 1].text(i, v + 0.4, f'{v:.0f}%', ha='center', fontsize=9)
    for (df, lab, c) in zip(dfs, labels, cpal):
        ax[1, 0].hist(df['sequence_length'].clip(upper=1000), bins=40, histtype='step', density=True, label=lab, color=c, lw=1.8)
    ax[1, 0].set_xlabel('sequence length (aa)')
    ax[1, 0].set_ylabel('density')
    ax[1, 0].set_title('Length distribution')
    ax[1, 0].legend(fontsize=8)
    for (df, lab, c) in zip(dfs, labels, cpal):
        ax[1, 1].hist(df['isoelectric_point'], bins=40, histtype='step', density=True, label=lab, color=c, lw=1.8)
    ax[1, 1].set_xlabel('isoelectric point')
    ax[1, 1].set_ylabel('density')
    ax[1, 1].set_title('Isoelectric-point distribution')
    ax[1, 1].legend(fontsize=8)
